/**
 * いぬのかお / Dog Face(全6工程)
 * https://www.origami-club.com/easy/animal-face/dogfase/zu.html を基準にした顔。
 *
 *   ❶ はんぶんに おる → 下向きの三角(折り線が上)
 *   ❷ 半分に折って折り目をつけ、開いて戻す(2工程)
 *   ❸ てんせんで おる → 左右の角を下へ折って、たれ耳(同時)
 *   ❹ てんせんで おる → 手前の1枚の下の先を折り上げる(裏の白が出る)
 *   ❺ てんせんで おる → 奥の1枚の先も折り上げる(表の色が出て、白は先だけのぞく)
 *
 * 2026-08-03 修正: 旧版は折り図を見ずに作っていたため、
 *   ① 耳の折り線が中心寄りでなく (±0.42,0) から始まり、頭が広く耳が小さかった
 *      (折り図は (±0.22,0) から。耳が大きく、先が紙の斜辺より外へ垂れる)
 *   ② ❷の「折り目をつけて戻す」工程が無かった
 *   ③ 最後が「手前を折り上げ+奥を裏へ山折り」で、原典の
 *      「手前を折り上げ→奥も折り上げて重ねる」(=マズルに白が少しだけのぞく)
 *      になっていなかった
 * の3点を折り図どおりに直した。
 *
 * 幾何の要点(折り図から実測):
 * - 耳の折り線は上辺の (∓0.22,0) から斜辺上の (∓0.67,∓0.33) へ。
 *   角(∓1,0)はこの線で (∓0.445,-0.742) へ回り、斜辺の外へ垂れる=たれ耳
 * - ❹の折り線は y=-0.72(斜辺との交点 (∓0.28,-0.72))。手前の先が y=-0.44 へ
 * - ❺の折り線は y=-0.75 と少し下。奥の先が y=-0.50 へ来るので、
 *   ❹の白い三角の先だけが上にのぞく(完成図の鼻先の白いすじ)
 *
 * 層の表現:
 * - ❶は山折り(上半分を奥へ)。動かない下半分が常に表を向く
 * - 耳・マズルはどちらも「2枚の層が一緒に約180°回る」ので、実物では
 *   奥の層が手前に来て表の色が見える。エンジンでは残差角の差で層順を作る
 *   (奥の層=小さい角度=より手前。shuriken.ts で確立したパターン)。
 *   そのため奥層の耳は頂点を複製する(14/15)
 */

const V: [number, number][] = [
  [0, 1], //  0: 上の角(❶で奥へ回り、❺で折り上げてマズルになる)
  [1, 0], //  1: 右の角(右耳・手前層)
  [0, -1], //  2: 下の角(❹で折り上げる=手前層のマズル)
  [-1, 0], //  3: 左の角(左耳・手前層)
  [-0.22, 0], //  4: 左耳の折り線・上端(❶の折り線上)
  [-0.67, -0.33], //  5: 左耳の折り線・下端(左下辺上)
  [0.22, 0], //  6: 右耳の折り線・上端
  [0.67, -0.33], //  7: 右耳の折り線・下端(右下辺上)
  [-0.67, 0.33], //  8: 左耳の折り線の上層ミラー(左上辺上)
  [0.67, 0.33], //  9: 右耳の折り線の上層ミラー(右上辺上)
  [-0.28, -0.72], // 10: ❹の折り線・左端(左下辺上)
  [0.28, -0.72], // 11: ❹の折り線・右端(右下辺上)
  [-0.25, 0.75], // 12: ❺の折り線の上層ミラー・左(左上辺上)
  [0.25, 0.75], // 13: ❺の折り線の上層ミラー・右(右上辺上)
  [-1, 0], // 14: 3 の上層複製(左耳・奥の層)
  [1, 0], // 15: 1 の上層複製(右耳・奥の層)
  [0, 0], // 16: 中心(❷の軸・❶の折り線上)
  [0, -0.72], // 17: ❹の折り線の中点
  [0, 0.75], // 18: ❺の折り線の中点(上層ミラー)
  // 19〜21: ❺で折り上げるマズル面だけが持つ複製。奥の層はヒンジ自体が
  // 手前の層より奥(z<0)にあるため、残差角の差だけでは手前に出せない。
  // 面ごと z 補正するので、胴側と共有しない専用の頂点にする
  // (=「z補正する頂点は、その面だけが持つ複製頂点にする」bear.ts の教訓)
  [-0.25, 0.75], // 19: 12 の複製
  [0.25, 0.75], // 20: 13 の複製
  [0, 0.75], // 21: 18 の複製
];

