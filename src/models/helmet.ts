/**
 * 兜 / Samurai Helmet(全7工程)
 * https://www.origami-club.com/fun/kabuto/zu.html を基準にした伝承の兜。
 *
 *   ❶ まんなかで半分に折る → 三角(折り線が上)
 *   ❷ 左右の角を中央へ折り下げる(同時) → ひし形
 *   ❸ 手前の先を、ひし形の横の対角線で上へ折り上げる(同時)
 *   ❹ 折り上げた先を斜め外へ開く(同時) → 左右のつの(くわがた)
 *   ❺ 手前の1枚の下の先を上へ折る
 *   ❻ 折り上げた先を、ひし形の横の対角線で下へ折り返す → 帯(前立て)
 *   ❼ 残った奥の先を中へ押し込む
 *
 * 2026-08-03 修正: 旧版は❸❹のつのを1回の折りにまとめ、帯も1回に簡略化した
 * 4工程だった。そのため つのが低く小さく(先が (∓0.5,-0.3))、兜に見えにくかった。
 * 原典どおり「先を対角線で上へ折り上げてから外へ開く」2段階に戻し、
 * 帯も「折り上げ→対角線で折り返し→奥を中へ」の3工程に戻した。
 *
 * 幾何の要点(折り図から実測):
 * - ❷の折り線は中心(0,0)から角の二等分線。左は y=x 上の (0,0)-(-0.5,-0.5) で、
 *   左の角(-1,0)はちょうど下の角(0,-1)へ重なる(厳密に一致)
 * - ❸の折り線はひし形の横の対角線 y=-0.5。展開図では x=∓0.5 の縦線
 *   ((∓0.5,0)-(∓0.5,∓0.5))。フラップの先(0,-1)はひし形の上の角(0,0)へ届く
 * - ❹の折り線は、折り上げた状態で (0,-0.5) から斜辺上の (∓0.17,-0.17) へ。
 *   展開図に戻すと (∓0.5,0)-(∓0.83,∓0.17)(=斜辺上)。
 *   つのの先は (∓0.407,-0.210) に来て、ひし形の斜辺の外へ張り出す
 * - ❺の折り線は y=-0.63、❻の折り返しは折り上げ後の y=-0.5(展開図では y=-0.76)
 *
 * 層の表現:
 * - ❶は山折り(上半分を奥へ)。動かない下半分が常に表を向く
 * - ❷以降のフラップは2枚重ねで回るので、実物では奥の層が手前に来て表の色が出る。
 *   エンジンでは残差角の差(奥=168°/手前=174°)で層順を作るため、
 *   奥層の角は頂点を複製する(21/22)
 */

