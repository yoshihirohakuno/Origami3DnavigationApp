/**
 * うさぎのかお / Rabbit Face(全7工程)
 * https://www.origami-club.com/easy/animal-face/rabbit/zu.html を基準にした顔。
 *
 *   ❶ はんぶんに おる → 色の三角(折り線が下)
 *   ❷ 半分に折って折り目をつけ、開いて戻す(2工程)
 *   ❸ 下端の帯を折り上げる(折り線 y=0.155)
 *   ❹ 左右の角を、あご先から45°で折り上げる(同時) → 長い耳
 *   ❺ うらがえす
 *   ❻ てっぺんを折って、頭の上をたいらにする
 *
 * 2026-08-04 修正: 旧版は原典❸の「下端の帯」を省略していた(3層になるため)。
 * その結果、耳が「あご先から出る三角」になっていたが、原典の耳は**幅0.155の
 * 細い帯**で、帯の外角がそのまま耳の先になる。帯を入れて折り図どおりに直した。
 *
 * 幾何の要点(折り図 ❺ の実測と厳密に一致):
 * - 帯の折り線は y=B=0.155。折り上げると紙の下の角 (∓1,0) は (∓1,0.31) へ来て、
 *   三角の斜辺より外へはみ出す(原典❹の図で帯が三角より広く描かれているのはこのため)
 * - 耳の折り線は あご先 (0,B) から 45°。斜辺との交点は (∓(1-B)/2,(1+B)/2)
 *   =(∓0.4225,0.5775)。これで耳を折った後の胴は**厳密な正方形のひし形**になる
 *   (下=(0,0.155) 上=(0,1) 左右=(∓0.4225,0.5775))
 * - 耳の折り線は帯の中も通る。帯を折り上げた状態では (0,B)→(∓0.155,0.31) なので、
 *   展開図に戻すと (0,B)→(∓0.155,0)(=帯の自由縁の上)。折り線は展開図では「くの字」
 * - 折り上がった耳は x∈[-0.155,0] と x∈[0,0.155] の細い帯2本。先は (∓0.155,1.155)
 *   で、上の辺が (0,1) から外上がりに走るので、2本の間に V の切れこみができる
 *   (完成図のうさぎの耳の形)
 * - ❻の折り線は y=0.8(ひし形の斜辺との交点が (∓0.2,0.8))
 *
 * 未実装: 原典❼「下の先を後ろへ折る」(折り線 y≈0.334)。あご先には
 * 胴2層+帯2層+耳4層が集まるので、全層を折り線で分割し直す必要がある。
 * 完成形のあごが平らな六角形でなく、とがったままになっている。
 *
 * 層の表現: ❶は山折り(下半分を奥へ)。帯・耳はどちらも2枚重ねで約180°回るので、
 * 実物では奥の層が手前に来る。エンジンでは残差角の差(奥=168°/手前=174°)で
 * 層順を作るため、下層の折り返し部分は頂点を複製する(24〜28)。
 */

const B = 0.155; // 帯の折り線の y
const BX = 1 - B; // 0.845 帯の折り線が斜辺と交わる x
const EX = (1 - B) / 2; // 0.4225 耳の折り線が斜辺と交わる x(絶対値)
const EY = (1 + B) / 2; // 0.5775 同 y
const T = 0.8; // ❻の折り線の y
const TX = 1 - T; // 0.2 ❻の折り線が斜辺と交わる x

const V: [number, number][] = [
  [0, 1], //  0: 上の角(てっぺん。❻で折る)
  [1, 0], //  1: 右の角(帯の一部→右耳の先)
  [-1, 0], //  2: 左の角(帯の一部→左耳の先)
  [0, 0], //  3: 中心(帯の自由縁の中点。❶の折り線上)
  [0, B], //  4: あご先(帯の折り線の中点=耳の折り線の起点)
  [-BX, B], //  5: 帯の折り線・左端(左上辺上)
  [BX, B], //  6: 帯の折り線・右端(右上辺上)
  [-0.155, 0], //  7: 左耳の折り線が帯の自由縁と交わる点
  [0.155, 0], //  8: 右耳
  [-EX, EY], //  9: 左耳の折り線・外端(左上辺上)
  [EX, EY], // 10: 右耳の折り線・外端(右上辺上)
  [-TX, T], // 11: ❻の折り線・左(左上辺上)
  [TX, T], // 12: ❻の折り線・右(右上辺上)
  [0, T], // 13: ❻の折り線の中点(❷の縦分割用)
  // 下層(❶で奥へ回る側)のミラー
  [0, -1], // 14: 上の角のミラー
  [-BX, -B], // 15: 帯の折り線・左端のミラー
  [BX, -B], // 16: 右端のミラー
  [0, -B], // 17: あご先のミラー
  [-EX, -EY], // 18: 左耳の折り線・外端のミラー
  [EX, -EY], // 19: 右耳のミラー
  [-TX, -T], // 20: ❻の折り線・左のミラー
  [TX, -T], // 21: ❻の折り線・右のミラー
  [0, -T], // 22: ❻の折り線の中点のミラー
  // 24〜28 ではなく 23〜27: ❶の折り線(y=0)上の頂点は両層で共有されるので、
  // 下層の帯・耳が手前に出る z 差(残差角の差)を作るために複製する
  [-1, 0], // 23: 2 の下層複製(左耳の先)
  [1, 0], // 24: 1 の下層複製(右耳の先)
  [0, 0], // 25: 3 の下層複製
  [-0.155, 0], // 26: 7 の下層複製
  [0.155, 0], // 27: 8 の下層複製
];

