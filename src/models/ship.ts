import type { FoldStep, OrigamiModel } from '../engine/types';

/**
 * ふね / Ship(全3工程)
 * https://www.origami-club.com/easy/vehicle/ship/zu.html の折り図に忠実。
 * 2026-08-12 追加。ヨットに続く2つめの「のりもの」。
 *
 *   ❶ てんせんで おる(下から 1/3 を手前へ折り上げる。裏の色が出て船体になる)
 *   ❷ てんせんで うしろに おる(白い部分の左上を斜め45°でうしろへ = 船室の前の傾き)
 *   ❸ てんせんで うしろに おる(左下の角を斜め45°でうしろへ = へさきの傾き)
 *
 * 幾何の要点(折り図のピクセル実測。紙は [-1,1] の正方形):
 * - ❶の折り線は **y=-1/3**(折り図に「1/3」と目盛りが入っている。実測 0.335)。
 *   折り上げた帯は y=-1/3〜+1/3 を覆うので、残りの白い部分とちょうど同じ幅になる
 * - ❷の折り線は **(1/3,1)→(-1,-1/3)** の45°線(実測 0.325 と -0.342 で ±1/3)。
 *   帯のふち(y=1/3)とは x=-1/3 で交わる。折り図の破線はそこで止まっているが、
 *   これは帯の下の紙が見えないだけで、折るのは白い層(下の層)だけ
 * - ❸の折り線は **(-1,1/3)→(-1/3,-1/3)** の45°線(折り後の座標)。帯の左上の角から
 *   下のふちの x=-1/3 へ。**帯と、その下に残っている白い層をまとめて**うしろへ折る
 * - 展開図では、帯(下の層)の折り線は❶の折り線で鏡映して **(-1,-1)→(-1/3,-1/3)**、
 *   白い層に残る分は **(-2/3,0)→(-1/3,-1/3)**(❷の折り線との交点から)になる
 *
 * 色: 白い面を上にして始め、❶で折り上げた裏(橙 #ffa800、折り図の実測)が船体になる。
 * 船室は白いまま(折り図❹と同じ)。
 *
 * 層: ❶で手前に来た帯が常に手前。❷❸はどちらもうしろへ折るので、
 * 前面には出てこない(残差角のままで層順が出る)。
 * **❷でうしろへ回る三角も❸の折り線で分割しておくこと**。分割しないと、
 * うしろへ回ったその三角の角が、❸で切り落とされたへさきの外へはみ出して
 * 裏の色のまま見える(実装時に実際にそう出た)。
 * ❷と❸の折り線は直交しているので、❸の折り線は❷で鏡映しても同じ直線に重なる。
 * 展開図では (-1,1/3)-(-2/3,0) の区間がその分割線になる。
 */

/** ❶の折り線(下から 1/3)。折り図の「1/3」の目盛り */
const B = -1 / 3;

const V: [number, number][] = [
  [-1, 1], // 0: 左上(❷でうしろへ回る)
  [1 / 3, 1], // 1: ❷の折り線・上端
  [1, 1], // 2: 右上
  [1, B], // 3: ❶の折り線・右端
  [-1 / 3, B], // 4: ❸の折り線・下端(❶の折り線の上。両層で共有)
  [-2 / 3, 0], // 5: ❷の折り線と❸の折り線の交点(白い層)
  [-1, B], // 6: ❶❷の折り線の左端(❸でうしろへ回る)
  [-1, -1], // 7: 左下(❶で折り上がり、❸の折り線の端になる)
  [1, -1], // 8: 右下(❶で折り上がる)
  [-1, -B], // 9: ❸の折り線が左のふちと交わる点(❷でうしろへ回る三角を分ける)
];

const F: number[][] = [
  // 白い層(❶で動かない上の 2/3)
  [0, 1, 5, 9], // ❷でうしろへ回る左上(❸の折り線より上)
  [9, 5, 6], // ❷でうしろへ回り、❸でもう一度回る角
  [6, 5, 4], // ❸でうしろへ回る左下の三角(帯の下に隠れている分)
  [5, 1, 2, 3, 4], // 船室になる本体
  // 帯(❶で折り上げる下の 1/3)
  [7, 4, 6], // ❸でうしろへ回る三角(へさき)
  [7, 8, 3, 4], // 船体
];

/** 反時計回り(表=+z)へ揃える */
function orient(f: number[]): number[] {
  let a = 0;
  for (let i = 0; i < f.length; i++) {
    const [x1, y1] = V[f[i]];
    const [x2, y2] = V[f[(i + 1) % f.length]];
    a += x1 * y2 - x2 * y1;
  }
  return a >= 0 ? f : [...f].reverse();
}

