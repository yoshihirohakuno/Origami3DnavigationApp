import type { FoldStep, OrigamiModel } from '../engine/types';

/**
 * しんかんせん / Bullet Train(全6工程)
 * https://www.origami-club.com/easy/vehicle/sinkansen/zu.html(作・図:新宮文明)
 *
 *   ❶ よこ半分に折り目をつけて戻す(2工程)
 *   ❷ 上下のふちを内へ折る(折り線 y=±F。裏の白が帯になって出る)
 *   ❸ よこ半分に**うしろへ**折る(残る手前の面が色のまま=折り図❹と同じ)
 *   ❹ 左の先を中割り折り → 鼻
 *   ❺ 鼻の下の角を内がわに折る
 *   ❻(折り図)まどを描いてできあがり = 折りではないので工程にしない
 *
 * 紙は [-1,1] の正方形。**色の面を上にして始める**(折り図❶❷が一面の青)。
 *
 * 幾何の要点(tools/zu-measure.mjs で実測。パネル名は折り図の丸数字):
 * - **❷の折り線 y=±F、F=0.72**。折り図に目印はなく「てんせんで おる」だけ。
 *   実測は ❷の破線から 0.727、❸の白い帯の比から 0.733、❹の青/白の比から 0.717、
 *   ❺の同じ比から 0.714、❻の同じ比から 0.694。**5パネルの平均 0.717 を採って 0.72**。
 * - ❸のあとは Y∈[-F,0] の横長の帯。上が折り目(背)、下が紙のふち。
 *   手前は「上が色・下が白い帯」で、白の高さは 1-F、色の高さは 2F-1(折り図❹と一致)
 * - **❹の中割り折りの折り線は、背のまんなか (0,0) から左のふちの (-1,-B)**。
 *   B=2F-1=0.44 は白い帯のさかいめで、折り図❹❺の破線はどちらもこの2点を結ぶ
 *   (実測: 背側の端 X=-0.05/-0.04、左のふち側 Y=-0.446/-0.411)。
 *   左上の角 (-1,0) はこの線で (-0.68,-0.74) へ回り、鼻の先になる
 * - **❺の折り線は (-1,-0.47)-(-0.822,-F)**(折り図❻の完成図の輪郭から実測。
 *   左のふちで F の 0.653 倍の高さ、下のふちで左から 0.178)。目印はない
 * - 完成形の縦横比 2.78(折り図❺の実測 2.92、❻の実測 2.96)
 *
 * 層(❹❺は全レイヤーを貫くので、折り線は層ごとに鏡映して展開図へ埋める):
 * - ❹の折り線は本体の2枚だけを通る(❷の帯は Y<-B なので当たらない)。
 *   下の層は 10-11、上の層は 10-12(y=0 で鏡映)
 * - ❺の折り線は4枚すべてを通る。下の本体 13-14 / 下の帯 17-14(y=-F で鏡映)/
 *   上の本体 15-16(y=0 で鏡映)/ 上の帯 18-16(さらに y=F で鏡映)
 * - ❸は山折り(上半分をうしろへ)。動かない下半分が表を向いたままになり、
 *   折り図❹の「上が色・下が白」がそのまま出る(谷折りにすると全面が白になる)
 */

/** ❷の折り線(実測 0.694〜0.733 の平均。折り図に目印なし) */
const F = 0.72;
/** ❷の帯のさかいめ = ❹の折り線が左のふちと交わる高さ */
const B = 2 * F - 1;
/** ❺の折り線が左のふちと交わる高さ(折り図❻の実測 0.653×F) */
const CY = 0.653 * F;
/** ❺の折り線が下のふちと交わる x(折り図❻の実測。左のふちから 0.178) */
const CX = -0.822;

const V: [number, number][] = [
  [-1, 1], //  0: 左上の角
  [1, 1], //  1: 右上の角
  [1, -1], //  2: 右下の角
  [-1, -1], //  3: 左下の角
  [-1, F], //  4: ❷の折り線・左(上)。❺で動く
  [1, F], //  5: ❷の折り線・右(上)
  [-1, -F], //  6: ❷の折り線・左(下)。❺で動く
  [1, -F], //  7: ❷の折り線・右(下)
  [-1, 0], //  8: ❸の折り線・左(❹で回って鼻の先になる)
  [1, 0], //  9: ❸の折り線・右
  [0, 0], // 10: ❸の折り線の中点(❹の折り線の背側の端)
  [-1, -B], // 11: ❹の折り線・左(下の層)
  [-1, B], // 12: ❹の折り線・左(上の層。❸で 11 に重なる)
  [-1, -CY], // 13: ❺の折り線・左(下の本体)
  [CX, -F], // 14: ❺の折り線・下(❷の折り線上)
  [-1, CY], // 15: ❺の折り線・左(上の本体)
  [CX, F], // 16: ❺の折り線・上(❷の折り線上。❸で 14 に重なる)
  [-1, -(2 * F - CY)], // 17: ❺の折り線・左(下の帯。y=-F で鏡映)
  [-1, 2 * F - CY], // 18: ❺の折り線・左(上の帯)
];

const F_: number[][] = [
  // 上の帯(❷でうしろ側=下へ折り返す)
  [0, 1, 5, 16, 18], // 帯の本体
  [18, 16, 4], // ❺で回る角
  // 上の本体(❸でうしろへ回る)
  [8, 10, 12], // ❹で回る鼻(上の層)
  [12, 10, 9, 5, 16, 15], // 胴
  [15, 16, 4], // ❺で回る角
  // 下の本体(動かない=完成形の手前)
  [8, 11, 10], // ❹で回る鼻(下の層)
  [11, 13, 14, 7, 9, 10], // 胴
  [13, 6, 14], // ❺で回る角
  // 下の帯(❷で上へ折り返す=完成形の白い帯)
  [17, 14, 6], // ❺で回る角
  [3, 2, 7, 14, 17], // 帯の本体
];

/** 反時計回り(表=+z)へ揃える */
function orient(f: number[]): number[] {
  let a = 0;
  for (let i = 0; i < f.length; i++) {
    const [x1, y1] = V[f[i]];
    const [x2, y2] = V[f[(i + 1) % f.length]];
    a += x1 * y2 - x2 * y1;
  }
  return a >= 0 ? f : [...f].reverse();
}

