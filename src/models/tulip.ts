import type { FoldStep, OrigamiModel } from '../engine/types';

/**
 * チューリップ(花) / Tulip(全6工程)
 * https://www.origami-club.com/easy/flowers/tulips/zu.html の花の部分に忠実。
 *
 *   ❶ はんぶんに おる → 三角(色が外)
 *   ❷ 半分に折って折り目をつけ、開いて戻す(2工程。中央の縦線が目印)
 *   ❸ 右の角を、まんなかの下から出る線で左へ折る
 *   ❹ 左の角も同じように右へ折る(❸の上に重なる)
 *   ❺ 下の先を、うしろへ折る
 *
 * 2026-08-09 作り直し: 旧版は3工程で、花びらを「上へ」折って先が上辺の外に
 * 少し出るだけだった(先 (±0.40,0.78))。原典の花びらは**中心を越えて反対側へ**
 * 折り、その先がチューリップの左右のとがりになる。折り図の実測(❺のパネル)と
 * 一致するよう作り直した。
 *
 * 幾何の要点(すべて厳密値。折り図の実測値を丸めた):
 * - ❶の後は三角形 (∓1,0)-(0,1)。底辺の中点が原点
 * - ❸の折り線は**原点から60°**の直線。紙のふち(x+y=1)との交点は
 *   ((√3-1)/2, (3-√3)/2) = (0.366,0.634)(折り図の実測 (0.34,0.644))
 * - 右の角 (1,0) は原点まわりに120°回って **(-0.5, √3/2)=(-0.5,0.866)** へ。
 *   左のふち(y=x+1)の外へ出て、これが左のとがりになる
 *   (折り図❺の実測 (-0.484,0.888) と一致)
 * - ❹は鏡写し。右のとがりは (0.5,0.866)。まんなかの角 (0,1) は両方の花びらの
 *   上のふちより高い位置に残るので、上が3つのとがりになる(原典の完成図と同じ)
 * - ❺の折り線は y=TIP=0.2(折り図の実測 0.215)。下の先(原点)だけが線より
 *   下にあり、6層すべてが「原点を頂点・底辺が折り線」の三角形になるので、
 *   `moving: [4, 14]` の1本の折りで全層をまとめて回せる(うさぎのあごと同じ)
 *
 * 層と色: ❶は山折り(下半分を奥へ)なので、手前は上半分=表(色)。
 * 花びらは2枚重ねで約180°回るため、**回した後は奥の層(下半分)が手前に来て、
 * その層は表を見せる**(原典の完成図が花びらまで色一色なのはこのため)。
 * エンジンでは残差角の差で層順を作るので、下層の花びらの角は層ごとに複製する
 * (19/20)。残差角は 右=上層176°/下層168°、左=上層174°/下層166° にして、
 * 後から折る左の花びらが右の上に重なるようにしてある(原典の折り順)。
 */

const P = (Math.sqrt(3) - 1) / 2; // 0.36603 ❸の折り線と紙のふちの交点 x
const Q = (3 - Math.sqrt(3)) / 2; // 0.63397 同 y(P+Q=1)
const TIP = 0.2; // ❺の折り線の y
const E = (TIP * P) / Q; // 0.11547 折り線が❸の折り線と交わる x
const E2 = 2 * E; // 0.23094 折り線が底辺と交わる x(花びらの層の折り線の端)

const V: [number, number][] = [
  [0, 1], //  0: 上の角(まんなかのとがり)
  [1, 0], //  1: 右の角(❸で左へ回る。上層)
  [0, -1], //  2: 0 のミラー(下層)
  [-1, 0], //  3: 左の角(❹で右へ回る。上層)
  [0, 0], //  4: 原点(上層の下の先。❺で後ろへ回る)
  [P, Q], //  5: ❸の折り線・外端(上層)
  [P, -Q], //  6: 5 のミラー(下層)
  [-P, Q], //  7: ❹の折り線・外端(上層)
  [-P, -Q], //  8: 7 のミラー(下層)
  // ❺の折り線の端点。層ごとに別の頂点になる(折り後に位置が一致する)
  [E, TIP], //  9: 上層・胴の右端(❸の折り線上)
  [-E, TIP], // 10: 上層・胴の左端(❹の折り線上)
  [0, TIP], // 11: 上層・胴の中央(❷の縦線上)
  [E2, 0], // 12: 上層・右の花びらの端(底辺上。❸で (-E,TIP) へ回る)
  [-E2, 0], // 13: 上層・左の花びらの端(❹で (E,TIP) へ回る)
  [0, 0], // 14: 原点(下層のコピー)
  [E, -TIP], // 15: 9 のミラー
  [-E, -TIP], // 16: 10 のミラー
  [0, -TIP], // 17: 11 のミラー
  [E2, 0], // 18: 12 の下層コピー
  [-E2, 0], // 19: 13 の下層コピー
  [1, 0], // 20: 1 の下層コピー(層ごとに残差角を変えるため)
  [-1, 0], // 21: 3 の下層コピー
];

